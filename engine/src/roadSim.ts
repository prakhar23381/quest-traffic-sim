import { CITY_IDM, equilibriumSpeed, idmAccel, type IdmParams } from "./idm";
import { ballisticStep } from "./integrate";
import { freeInsertionSpeed, insertionSpeed } from "./insertion";
import { Lane, type Vehicle } from "./lane";
import { Rng } from "./rng";
import { fnv1aFloat64 } from "./hash";

/**
 * Phase-1 simulator: one lane, either an open road (source at 0, sink at the
 * end) or a ring road. The network simulator (Phase 2) reuses the same IDM,
 * integrator and Lane pieces; this class exists to validate them in isolation.
 */
export interface RoadSimConfig {
  length: number;
  ring?: boolean;
  seed?: number;
  /** time step, s */
  dt?: number;
  driver?: Partial<IdmParams>;
  /** vehicle length, m */
  vehLen?: number;
  /** open road only: Poisson demand at the entrance, veh/s */
  inflow?: number;
  /** ring only: number of vehicles placed uniformly at t = 0 */
  ringVehicles?: number;
  /** ring only: initial position offset of vehicle 0, m (seeds instabilities) */
  ringPerturbation?: number;
  /** detector positions (point loops), m from lane start */
  detectors?: number[];
}

export interface DetectorReading {
  pos: number;
  count: number;
  /** sum of speeds of crossing vehicles (for time-mean speed) */
  speedSum: number;
}

export class RoadSim {
  readonly dt: number;
  readonly lane: Lane;
  readonly params: IdmParams;
  readonly vehLen: number;
  readonly rng: Rng;
  time = 0;

  /** vehicles generated by demand (includes those still waiting to enter) */
  generated = 0;
  /** vehicles that physically entered the road */
  entered = 0;
  exited = 0;
  /** travel times of exited vehicles, s */
  readonly travelTimes: number[] = [];
  /** smallest bumper-to-bumper gap observed over the run, m */
  minGapSeen = Infinity;
  /** set if any speed ever goes negative or non-finite */
  badState = false;

  readonly detectors: DetectorReading[];
  private readonly inflow: number;
  private nextArrival: number;
  private nextId = 0;
  private readonly scratch = { v: 0 };

  constructor(cfg: RoadSimConfig) {
    this.dt = cfg.dt ?? 0.25;
    this.lane = new Lane(cfg.length, cfg.ring ?? false);
    this.params = { ...CITY_IDM, ...cfg.driver };
    this.vehLen = cfg.vehLen ?? 4.5;
    this.rng = new Rng(cfg.seed ?? 1);
    this.inflow = cfg.ring ? 0 : (cfg.inflow ?? 0);
    this.nextArrival = this.rng.exp(this.inflow);
    this.detectors = (cfg.detectors ?? []).map((pos) => ({ pos, count: 0, speedSum: 0 }));

    if (this.lane.ring && cfg.ringVehicles) this.placeRing(cfg.ringVehicles, cfg.ringPerturbation ?? 0);
  }

  /** vehicles generated but not yet able to enter (virtual queue at the entrance) */
  get waiting(): number {
    return this.generated - this.entered;
  }

  get inNetwork(): number {
    return this.lane.vehicles.length;
  }

  private makeVehicle(pos: number, v: number): Vehicle {
    return { id: this.nextId++, pos, v, acc: 0, len: this.vehLen, params: this.params, tSpawn: this.time };
  }

  private placeRing(n: number, perturbation: number): void {
    const L = this.lane.length;
    const spacing = L / n;
    if (spacing <= this.vehLen) throw new Error(`Ring too dense: ${n} vehicles of ${this.vehLen} m on ${L} m`);
    const vEq = equilibriumSpeed(this.params, spacing - this.vehLen);
    for (let i = 0; i < n; i++) {
      const pos = this.vehLen + i * spacing + (i === 0 ? perturbation : 0);
      this.lane.vehicles.push(this.makeVehicle(pos, vEq));
    }
    this.entered = this.generated = n;
  }

  step(): void {
    const dt = this.dt;
    const vs = this.lane.vehicles;
    const L = this.lane.length;

    // 1. Demand: Poisson arrivals join the entrance queue.
    while (this.nextArrival <= this.time) {
      this.generated++;
      this.nextArrival += this.rng.exp(this.inflow);
    }

    // 2. Accelerations from the current state (synchronous update).
    for (let i = 0; i < vs.length; i++) {
      const veh = vs[i]!;
      const ld = this.lane.leaderOf(i);
      veh.acc = ld ? idmAccel(veh.params, veh.v, ld.gap, ld.vLead) : idmAccel(veh.params, veh.v, 0, null);
    }

    // 3. Move vehicles; count detector crossings.
    for (const veh of vs) {
      const before = veh.pos;
      const vBefore = veh.v;
      veh.pos += ballisticStep(veh.v, veh.acc, dt, this.scratch);
      veh.v = this.scratch.v;
      if (!(veh.v >= 0) || !Number.isFinite(veh.pos)) this.badState = true;
      for (const d of this.detectors) {
        if (crossed(before, veh.pos, d.pos, L, this.lane.ring)) {
          d.count++;
          d.speedSum += 0.5 * (vBefore + veh.v);
        }
      }
    }

    // 4. Boundary handling.
    if (this.lane.ring) {
      // Vehicles past the end wrap to the start; they are the most downstream,
      // so move them from the back of the array to the front to keep it sorted.
      while (vs.length > 0 && vs[vs.length - 1]!.pos >= L) {
        const veh = vs.pop()!;
        veh.pos -= L;
        vs.unshift(veh);
      }
    } else {
      while (vs.length > 0 && vs[vs.length - 1]!.pos - vs[vs.length - 1]!.len >= L) {
        const veh = vs.pop()!;
        this.exited++;
        this.travelTimes.push(this.time + dt - veh.tSpawn);
      }
    }

    // 5. Insert at most one waiting vehicle at the entrance.
    if (!this.lane.ring && this.waiting > 0) this.tryInsert();

    // 6. Invariant tracking.
    const g = this.lane.minGap();
    if (g < this.minGapSeen) this.minGapSeen = g;

    this.time += dt;
  }

  /** Insert a waiting vehicle with its front at pos = 0 if there is room (see insertion.ts). */
  private tryInsert(): void {
    const vs = this.lane.vehicles;
    let v: number | null;
    if (vs.length === 0) {
      v = freeInsertionSpeed(this.params);
    } else {
      const first = vs[0]!;
      v = insertionSpeed(this.params, first.pos - first.len, first.v);
    }
    if (v === null) return; // no room; vehicle keeps waiting
    vs.unshift(this.makeVehicle(0, v));
    this.entered++;
  }

  run(seconds: number): void {
    const steps = Math.round(seconds / this.dt);
    for (let i = 0; i < steps; i++) this.step();
  }

  /** Space-mean speed over all vehicles, m/s. */
  meanSpeed(): number {
    const vs = this.lane.vehicles;
    if (vs.length === 0) return 0;
    let s = 0;
    for (const v of vs) s += v.v;
    return s / vs.length;
  }

  /** Hash of the full dynamic state, for determinism / parity checks. */
  stateHash(): string {
    const vs = this.lane.vehicles;
    const buf = new Float64Array(4 + 2 * vs.length);
    buf[0] = this.time;
    buf[1] = this.generated;
    buf[2] = this.entered;
    buf[3] = this.exited;
    vs.forEach((v, i) => {
      buf[4 + 2 * i] = v.pos;
      buf[5 + 2 * i] = v.v;
    });
    return fnv1aFloat64(buf);
  }
}

/** Did a vehicle moving from `a` to `b` cross point `x` on a lane of length L? */
function crossed(a: number, b: number, x: number, L: number, ring: boolean): boolean {
  if (!ring || b < L) return a < x && b >= x;
  // Wrapped this step: crossed if x is in (a, L) or in [0, b - L].
  return x > a || x <= b - L;
}
